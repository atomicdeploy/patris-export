function websocketURL(asyncapi) {
  const channel = asyncAPIChannels(asyncapi).find((entry) => entry.path === '/ws');
  const server = asyncapi.servers?.integrationLoopback
    ?? Object.values(asyncapi.servers ?? {})[0];
  if (!channel || !server?.host) {
    return undefined;
  }
  const protocol = server.protocol === 'wss' ? 'wss' : 'ws';
  const basePath = String(server.pathname ?? '').replace(/^\/|\/$/g, '');
  const route = String(channel.path).replace(/^\/+/, '');
  const joined = basePath === route
    ? route
    : [basePath, route].filter(Boolean).join('/');
  return `${protocol}://${server.host}/${joined}`;
}

