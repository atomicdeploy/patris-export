function readDocument(file) {
  const text = fs.readFileSync(file, 'utf8');
  if (path.extname(file).toLowerCase() === '.json') {
    return JSON.parse(text);
  }
  return YAML.parse(text);
}

function writeText(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, String(text).replace(/\r\n/g, '\n'), 'utf8');
}

function stableObject(value) {
  if (Array.isArray(value)) {
    return value.map(stableObject);
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort((left, right) => left.localeCompare(right))
        .map((key) => [key, stableObject(value[key])]),
    );
  }
  return value;
}

function stableJSON(value, indent = 2) {
  return `${JSON.stringify(stableObject(value), null, indent)}\n`;
}

function stableYAML(value) {
  return YAML.stringify(stableObject(value), {
    lineWidth: 0,
    sortMapEntries: true,
  });
}

function sha256Buffer(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function sha256File(file) {
  return sha256Buffer(fs.readFileSync(file));
}

function repositoryCommit(repoRoot) {
  const result = spawnSync(
    'git',
    ['-C', path.resolve(repoRoot), 'rev-parse', '--verify', 'HEAD^{commit}'],
    { encoding: 'utf8', windowsHide: true },
  );
  const revision = result.status === 0 ? result.stdout.trim().toLowerCase() : '';
  return /^[0-9a-f]{40}$/.test(revision) ? revision : null;
}

function listFiles(root) {
  const files = [];
  if (!fs.existsSync(root)) {
    return files;
  }
  const visit = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })
      .sort((left, right) => left.name.localeCompare(right.name))) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        visit(absolute);
      } else if (entry.isFile()) {
        files.push(absolute);
      }
    }
  };
  visit(root);
  return files;
}

function posixRelative(root, file) {
  return path.relative(root, file).split(path.sep).join('/');
}

function treeDigest(root, excluded = new Set()) {
  const hash = crypto.createHash('sha256');
  for (const file of listFiles(root)) {
    const relative = posixRelative(root, file);
    if (excluded.has(relative)) {
      continue;
    }
    hash.update(relative);
    hash.update('\0');
    hash.update(fs.readFileSync(file));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function escapeHTML(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function markdownText(value) {
  return String(value ?? '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[`*_>#]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeMuxPath(route) {
  return route.replace(/\{([^}:]+):[^}]+\}/g, '{$1}');
}

function parseServerRoutes(sourceText) {
  const routes = [];
  const routerCalls = [...sourceText.matchAll(/s\.router\.([A-Za-z][A-Za-z0-9_]*)\s*\(/g)];
  const unsupportedCalls = [...new Set(
    routerCalls
      .map((call) => call[1])
      .filter((method) => method !== 'HandleFunc'),
  )].sort();
  if (unsupportedCalls.length) {
    throw new Error(
      `Unsupported router registration method(s): ${unsupportedCalls.join(', ')}. Extend the API route auditor before adding routes with this syntax.`,
    );
  }
  const registration = /s\.router\.HandleFunc\(\s*"([^"]+)"\s*,\s*(s\.([A-Za-z_][A-Za-z0-9_]*))\s*\)(?:\.Methods\(([^)]*)\))?/g;
  let match;
  let parsedRegistrations = 0;
  while ((match = registration.exec(sourceText)) !== null) {
    parsedRegistrations += 1;
    const sourcePath = match[1];
    const normalizedPath = normalizeMuxPath(sourcePath);
    const handler = `Server.${match[3]}`;
    const rawMethods = match[4];
    if (!rawMethods) {
      if (normalizedPath !== '/ws') {
        throw new Error(`Route ${sourcePath} does not declare methods and is not the supported /ws upgrade route.`);
      }
      routes.push({
        kind: 'websocket',
        path: normalizedPath,
        sourcePath,
        handler,
      });
      continue;
    }

    const methods = [...rawMethods.matchAll(/"([A-Z]+)"/g)].map((method) => method[1]);
    if (methods.length === 0) {
      throw new Error(`Route ${sourcePath} has an empty Methods registration.`);
    }
    for (const method of methods) {
      routes.push({
        kind: 'http',
        method,
        path: normalizedPath,
        sourcePath,
        handler,
      });
    }
  }
  if (parsedRegistrations !== routerCalls.length) {
    throw new Error(
      `Parsed ${parsedRegistrations} of ${routerCalls.length} s.router.HandleFunc registrations. Extend the API route auditor before using non-literal paths or handlers.`,
    );
  }
  if (routes.length === 0) {
    throw new Error('No s.router.HandleFunc registrations were found in pkg/server/server.go.');
  }
  return routes;
}

function openAPIOperations(openapi) {
  const operations = [];
  for (const [route, pathItem] of Object.entries(openapi.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem ?? {})) {
      if (HTTP_METHODS.has(method.toLowerCase())) {
        operations.push({
          kind: 'http',
          method: method.toUpperCase(),
          path: route,
          operation,
          pathItem,
        });
      }
    }
  }
  return operations;
}

function asyncAPIChannels(asyncapi) {
  return Object.entries(asyncapi.channels ?? {}).map(([key, channel]) => ({
    key,
    path: channel?.address || (key.startsWith('/') ? key : undefined),
    channel,
  }));
}

function routeKey(route) {
  return `${route.method} ${route.path}`;
}

function assertRouteParity({ sourceText, openapi, asyncapi }) {
  const sourceRoutes = parseServerRoutes(sourceText);
  const sourceHTTP = new Set(
    sourceRoutes.filter((route) => route.kind === 'http').map(routeKey),
  );
  const documentedHTTP = new Set(openAPIOperations(openapi).map(routeKey));

  const missingHTTP = [...sourceHTTP].filter((key) => !documentedHTTP.has(key)).sort();
  const staleHTTP = [...documentedHTTP].filter((key) => !sourceHTTP.has(key)).sort();

  const sourceWebSockets = new Set(
    sourceRoutes.filter((route) => route.kind === 'websocket').map((route) => route.path),
  );
  const documentedWebSockets = new Set(
    asyncAPIChannels(asyncapi).map((channel) => channel.path).filter(Boolean),
  );
  const missingWebSockets = [...sourceWebSockets]
    .filter((route) => !documentedWebSockets.has(route))
    .sort();
  const staleWebSockets = [...documentedWebSockets]
    .filter((route) => !sourceWebSockets.has(route))
    .sort();

  if (missingHTTP.length || staleHTTP.length || missingWebSockets.length || staleWebSockets.length) {
    const details = [
      missingHTTP.length ? `Missing OpenAPI operations:\n  - ${missingHTTP.join('\n  - ')}` : '',
      staleHTTP.length ? `OpenAPI operations without a server registration:\n  - ${staleHTTP.join('\n  - ')}` : '',
      missingWebSockets.length ? `Missing AsyncAPI channels:\n  - ${missingWebSockets.join('\n  - ')}` : '',
      staleWebSockets.length ? `AsyncAPI channels without a server registration:\n  - ${staleWebSockets.join('\n  - ')}` : '',
    ].filter(Boolean);
    throw new Error(`API documentation/source route parity failed.\n${details.join('\n')}`);
  }

  return {
    httpOperations: sourceHTTP.size,
    websocketChannels: sourceWebSockets.size,
  };
}

function assertVersionParity({ sourceText, openapi, asyncapi }) {
  const match = sourceText.match(/\bVersion\s*=\s*"([^"]+)"/);
  if (!match) {
    throw new Error('Unable to read the product version from pkg/version/version.go.');
  }
  const productVersion = match[1];
  const mismatches = [
    ['OpenAPI', openapi?.info?.version],
    ['AsyncAPI', asyncapi?.info?.version],
  ].filter(([, version]) => version !== productVersion);
  if (mismatches.length) {
    throw new Error([
      `API documentation version parity failed; product version is ${productVersion}.`,
      ...mismatches.map(([contract, version]) => `  - ${contract}: ${version ?? '(missing)'}`),
    ].join('\n'));
  }
  return productVersion;
}

const CODE_ANCHOR_PATTERN = /^([^#]+)#([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)?)$/;

function declarationPattern(symbol) {
  const method = symbol.match(/^([A-Za-z_][A-Za-z0-9_]*)\.([A-Za-z_][A-Za-z0-9_]*)$/);
  if (method) {
    const [, receiver, name] = method;
    return new RegExp(
      `^\\s*func\\s*\\(\\s*[A-Za-z_][A-Za-z0-9_]*\\s+\\*?${receiver}\\s*\\)\\s*${name}\\s*(?:\\[[^\\]]+\\]\\s*)?\\(`,
      'm',
    );
  }
  return new RegExp(
    `^\\s*(?:func\\s+${symbol}\\s*(?:\\[[^\\]]+\\]\\s*)?\\(|type\\s+${symbol}\\s+)`,
    'm',
  );
}

function validateCodeAnchor(anchor, repoRoot, context, cache) {
  if (!nonemptyText(anchor)) {
    return `${context} has an empty x-code-anchors entry.`;
  }
  const match = anchor.match(CODE_ANCHOR_PATTERN);
  if (!match) {
    return `${context} code anchor ${JSON.stringify(anchor)} must use repo/path.go#Symbol or repo/path.go#Receiver.method; numeric line anchors are forbidden.`;
  }
  const [, relativePath, symbol] = match;
  if (
    path.isAbsolute(relativePath)
    || relativePath.includes('\\')
    || relativePath.split('/').includes('..')
    || path.extname(relativePath) !== '.go'
  ) {
    return `${context} code anchor ${JSON.stringify(anchor)} must point to a repo-relative Go source file without traversal.`;
  }
  const root = path.resolve(repoRoot);
  const sourceFile = path.resolve(root, ...relativePath.split('/'));
  if (sourceFile !== root && !sourceFile.startsWith(`${root}${path.sep}`)) {
    return `${context} code anchor ${JSON.stringify(anchor)} escapes the repository root.`;
  }
  if (!fs.existsSync(sourceFile) || !fs.statSync(sourceFile).isFile()) {
    return `${context} code anchor ${JSON.stringify(anchor)} points to a missing source file.`;
  }
  if (path.basename(sourceFile).endsWith('_test.go')) {
    return `${context} code anchor ${JSON.stringify(anchor)} must point to runtime source, not a test file.`;
  }
  let sourceText = cache.get(sourceFile);
  if (sourceText === undefined) {
    sourceText = fs.readFileSync(sourceFile, 'utf8');
    cache.set(sourceFile, sourceText);
  }
  if (!declarationPattern(symbol).test(sourceText)) {
    return `${context} code anchor ${JSON.stringify(anchor)} does not resolve to an exact Go declaration.`;
  }
  return undefined;
}

function assertCodeAnchors({ repoRoot, sourceText, openapi, asyncapi }) {
  const errors = [];
  const cache = new Map();
  const sourceRoutes = parseServerRoutes(sourceText);
  const httpHandlers = new Map(
    sourceRoutes
      .filter((route) => route.kind === 'http')
      .map((route) => [routeKey(route), route.handler]),
  );
  const websocketHandlers = new Map(
    sourceRoutes
      .filter((route) => route.kind === 'websocket')
      .map((route) => [route.path, route.handler]),
  );

  const checkAnchors = (anchors, context, requiredSymbol) => {
    if (!Array.isArray(anchors) || anchors.length === 0) {
      errors.push(`${context} must define at least one x-code-anchors entry.`);
      return;
    }
    const unique = new Set();
    const symbols = new Set();
    for (const anchor of anchors) {
      if (unique.has(anchor)) {
        errors.push(`${context} duplicates code anchor ${JSON.stringify(anchor)}.`);
        continue;
      }
      unique.add(anchor);
      const match = typeof anchor === 'string' ? anchor.match(CODE_ANCHOR_PATTERN) : null;
      if (match) {
        symbols.add(match[2]);
      }
      const error = validateCodeAnchor(anchor, repoRoot, context, cache);
      if (error) {
        errors.push(error);
      }
    }
    if (requiredSymbol && !symbols.has(requiredSymbol)) {
      errors.push(`${context} must anchor its registered handler ${requiredSymbol}.`);
    }
  };

  for (const entry of openAPIOperations(openapi)) {
    const label = `${entry.method} ${entry.path}`;
    checkAnchors(
      entry.operation?.['x-code-anchors'],
      label,
      httpHandlers.get(routeKey(entry)),
    );
  }

  for (const entry of asyncAPIChannels(asyncapi)) {
    const context = `AsyncAPI channel ${entry.path ?? entry.key}`;
    checkAnchors(
      entry.channel?.['x-code-anchors'],
      context,
      websocketHandlers.get(entry.path),
    );
  }

  for (const [key, operation] of Object.entries(asyncapi.operations ?? {})) {
    checkAnchors(operation?.['x-code-anchors'], `AsyncAPI operation ${key}`);
  }

  if (errors.length) {
    throw new Error(`API source code anchor validation failed.\n  - ${errors.join('\n  - ')}`);
  }
}

function visibilityOf(operation, parent) {
  return operation?.['x-visibility'] ?? parent?.['x-visibility'];
}

function validVisibility(value) {
  return typeof value === 'string'
    && VISIBILITY_PREFIXES.some((prefix) => value === prefix || value.startsWith(`${prefix}-`));
}

function externallyDocumented(operation, parent) {
  const marker = operation?.['x-internal'] ?? parent?.['x-internal'];
  return marker === false;
}

function assertVisibility(openapi, asyncapi) {
  const errors = [];
  for (const entry of openAPIOperations(openapi)) {
    const visibility = visibilityOf(entry.operation, entry.pathItem);
    if (!validVisibility(visibility)) {
      errors.push(`${entry.method} ${entry.path} must set x-visibility to a public-, protected-, internal-, or private-prefixed classification.`);
    }
    if (typeof (entry.operation?.['x-internal'] ?? entry.pathItem?.['x-internal']) !== 'boolean') {
      errors.push(`${entry.method} ${entry.path} must set x-internal to true or false.`);
    }
  }

  const asyncVersion = String(asyncapi.asyncapi ?? '');
  if (asyncVersion.startsWith('3.')) {
    for (const [key, channel] of Object.entries(asyncapi.channels ?? {})) {
      const visibility = channel?.['x-visibility'];
      if (!validVisibility(visibility)) {
        errors.push(`AsyncAPI channel ${channel?.address || key} must set x-visibility.`);
      }
      if (typeof channel?.['x-internal'] !== 'boolean') {
        errors.push(`AsyncAPI channel ${channel?.address || key} must set x-internal to true or false.`);
      }
    }
    for (const [key, operation] of Object.entries(asyncapi.operations ?? {})) {
      const referencedChannel = resolveLocalRef(asyncapi, operation?.channel?.$ref);
      const visibility = visibilityOf(operation, referencedChannel);
      if (!validVisibility(visibility)) {
        errors.push(`AsyncAPI operation ${key} must set x-visibility or inherit it from its channel.`);
      }
    }
  } else {
    for (const [key, channel] of Object.entries(asyncapi.channels ?? {})) {
      for (const action of ['publish', 'subscribe']) {
        if (!channel?.[action]) {
          continue;
        }
        const visibility = visibilityOf(channel[action], channel);
        if (!validVisibility(visibility)) {
          errors.push(`AsyncAPI ${action} operation on ${key} must set x-visibility.`);
        }
      }
    }
  }

  if (errors.length) {
    throw new Error(`API visibility validation failed.\n  - ${errors.join('\n  - ')}`);
  }
}

function hasOwn(object, key) {
  return Object.prototype.hasOwnProperty.call(object ?? {}, key);
}

function nonemptyText(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function hasExample(value, document, seen = new Set()) {
  if (!value || typeof value !== 'object') {
    return false;
  }
  if (
    hasOwn(value, 'example')
    || hasOwn(value, 'default')
    || hasOwn(value, 'const')
    || (value.examples && Object.keys(value.examples).length > 0)
  ) {
    return true;
  }
  if (value.$ref && !seen.has(value.$ref)) {
    const resolved = resolveLocalObject(document, value, seen);
    const nextSeen = new Set(seen);
    nextSeen.add(value.$ref);
    return hasExample(resolved, document, nextSeen);
  }
  if (value.schema) {
    return hasExample(value.schema, document, seen);
  }
  // A leaf/property example is not a complete request or response instance.
  // Media entries and their resolved top-level schemas must carry an example
  // of the entire payload so examples cannot silently omit wrapper fields.
  return false;
}

function isBinaryMedia(mediaType, media) {
  const schema = media?.schema;
  return mediaType.startsWith('image/')
    || mediaType.startsWith('audio/')
    || mediaType === 'application/octet-stream'
    || schema?.format === 'binary';
}

function validateMediaMap({ content, context, document, allowEmpty = false }) {
  const errors = [];
  const entries = Object.entries(content ?? {});
  if (!entries.length) {
    if (!allowEmpty) {
      errors.push(`${context} must document at least one response/request media type.`);
    }
    return errors;
  }
  for (const [mediaType, media] of entries) {
    if (!mediaType.includes('/')) {
      errors.push(`${context} has invalid media type ${mediaType}.`);
    }
    if (!media?.schema) {
      errors.push(`${context} ${mediaType} must define a schema.`);
      continue;
    }
    if (!isBinaryMedia(mediaType, media) && !hasExample(media, document)) {
      errors.push(`${context} ${mediaType} must define a sanitized example at the media or schema level.`);
    }
    const synchronizedConfig = media?.['x-example-config-schema'];
    if (synchronizedConfig) {
      const schema = resolveLocalRef(document, synchronizedConfig);
      if (!schema?.example) {
        errors.push(`${context} ${mediaType} x-example-config-schema must resolve to a schema with an example.`);
      } else if (stableJSON(media?.example?.config) !== stableJSON(schema.example)) {
        errors.push(`${context} ${mediaType} example.config must exactly match ${synchronizedConfig}.example.`);
      }
    }
  }
  return errors;
}

function assertCompleteness(openapi, asyncapi) {
  const errors = [];
  const operationIds = new Set();
  for (const entry of openAPIOperations(openapi)) {
    const label = `${entry.method} ${entry.path}`;
    const operation = entry.operation;
    if (!nonemptyText(operation.operationId)) {
      errors.push(`${label} must define operationId.`);
    } else if (operationIds.has(operation.operationId)) {
      errors.push(`${label} duplicates operationId ${operation.operationId}.`);
    } else {
      operationIds.add(operation.operationId);
    }
    if (!nonemptyText(operation.summary)) {
      errors.push(`${label} must define a summary.`);
    }
    if (!nonemptyText(operation.description)) {
      errors.push(`${label} must define a description.`);
    }
    if (!hasOwn(operation, 'x-visibility') || !validVisibility(operation['x-visibility'])) {
      errors.push(`${label} must explicitly define x-visibility.`);
    }
    if (!hasOwn(operation, 'x-internal') || typeof operation['x-internal'] !== 'boolean') {
      errors.push(`${label} must explicitly define x-internal as true or false.`);
    }
    if (!hasOwn(operation, 'security') || !Array.isArray(operation.security)) {
      errors.push(`${label} must explicitly define security (use security: [] when unauthenticated).`);
    }

    const parameters = [...(entry.pathItem.parameters ?? []), ...(operation.parameters ?? [])];
    for (const rawParameter of parameters) {
      const parameterLabel = `${label} parameter ${rawParameter?.name ?? rawParameter?.$ref ?? '(unknown)'}`;
      let parameter;
      try {
        parameter = resolveLocalObject(openapi, rawParameter);
      } catch (error) {
        errors.push(`${parameterLabel}: ${error.message}`);
        continue;
      }
      if (!nonemptyText(parameter?.description)) {
        errors.push(`${parameterLabel} must define a description.`);
      }
      if (!parameter?.schema && !parameter?.content) {
        errors.push(`${parameterLabel} must define a schema or content.`);
      }
      if (
        parameter?.required
        && parameter?.in !== 'header'
        && !hasExample(parameter, openapi)
      ) {
        errors.push(`${parameterLabel} is required and must define an example.`);
      }
    }

    if (operation.requestBody) {
      let requestBody;
      try {
        requestBody = resolveLocalObject(openapi, operation.requestBody);
      } catch (error) {
        errors.push(`${label} requestBody: ${error.message}`);
      }
      if (!nonemptyText(requestBody?.description)) {
        errors.push(`${label} requestBody must define a description.`);
      }
      errors.push(...validateMediaMap({
        content: requestBody?.content,
        context: `${label} requestBody`,
        document: openapi,
      }));
    }

    const responses = Object.entries(operation.responses ?? {});
    if (!responses.length) {
      errors.push(`${label} must document responses.`);
      continue;
    }
    const statuses = responses.map(([status]) => status.toUpperCase());
    const redirectOnly = operation['x-redirect-only'] === true;
    const hasSuccess = statuses.some((status) => /^2(?:\d\d|XX)$/.test(status));
    const hasRedirect = statuses.some((status) => /^3(?:\d\d|XX)$/.test(status));
    if (!hasSuccess && !redirectOnly) {
      errors.push(`${label} must document at least one 2xx response.`);
    }
    if (redirectOnly && (hasSuccess || !hasRedirect)) {
      errors.push(`${label} marked x-redirect-only must document a 3xx response and no 2xx response.`);
    }
    const errorsNotApplicable = operation['x-errors-not-applicable'] === true;
    if (!errorsNotApplicable && !statuses.some((status) => /^4(?:\d\d|XX)$/.test(status))) {
      errors.push(`${label} must document a 4xx response or set x-errors-not-applicable: true.`);
    }
    if (!errorsNotApplicable && !statuses.some((status) => /^5(?:\d\d|XX)$/.test(status))) {
      errors.push(`${label} must document a 5xx response or set x-errors-not-applicable: true.`);
    }

    for (const [status, rawResponse] of responses) {
      const responseLabel = `${label} response ${status}`;
      let response;
      try {
        response = resolveLocalObject(openapi, rawResponse);
      } catch (error) {
        errors.push(`${responseLabel}: ${error.message}`);
        continue;
      }
      if (!nonemptyText(response?.description)) {
        errors.push(`${responseLabel} must define a description.`);
      }
      for (const [headerName, rawHeader] of Object.entries(response?.headers ?? {})) {
        let header;
        try {
          header = resolveLocalObject(openapi, rawHeader);
        } catch (error) {
          errors.push(`${responseLabel} header ${headerName}: ${error.message}`);
          continue;
        }
        if (!nonemptyText(header?.description) || (!header?.schema && !header?.content)) {
          errors.push(`${responseLabel} header ${headerName} must define a description and schema/content.`);
        }
      }
      const explicitlyBodyless = response?.['x-bodyless'] === true;
      if (explicitlyBodyless && response?.content && Object.keys(response.content).length > 0) {
        errors.push(`${responseLabel} is marked x-bodyless but also defines content.`);
      }
      const bodyless = entry.method === 'HEAD' || status === '204' || status === '304' || explicitlyBodyless;
      errors.push(...validateMediaMap({
        content: response?.content,
        context: responseLabel,
        document: openapi,
        allowEmpty: bodyless,
      }));
    }
  }

  const ws = asyncAPIChannels(asyncapi).find((channel) => channel.path === '/ws');
  if (!ws) {
    errors.push('AsyncAPI must define the /ws channel.');
  } else {
    const operations = asyncOperationsForChannel(asyncapi, ws.key, ws.channel);
    const actions = new Set(operations.map((operation) => operation.action));
    const requiredActions = String(asyncapi.asyncapi ?? '').startsWith('3.')
      ? ['send', 'receive']
      : ['publish', 'subscribe'];
    for (const action of requiredActions) {
      if (!actions.has(action)) {
        errors.push(`AsyncAPI /ws must define a ${action} operation.`);
      }
    }
    for (const operation of operations) {
      if (!nonemptyText(operation.summary) || !nonemptyText(operation.description)) {
        errors.push(`AsyncAPI /ws ${operation.action ?? operation.key} operation must define summary and description.`);
      }
    }
    const messages = Object.entries(ws.channel?.messages ?? {});
    if (!messages.length) {
      errors.push('AsyncAPI /ws must define channel messages.');
    }
    for (const [name, messageReference] of messages) {
      if (!messageReference?.$ref) {
        errors.push(`AsyncAPI /ws message ${name} must use a $ref.`);
        continue;
      }
      let message;
      try {
        message = resolveLocalObject(asyncapi, messageReference);
      } catch (error) {
        errors.push(`AsyncAPI /ws message ${name}: ${error.message}`);
        continue;
      }
      if (!message) {
        errors.push(`AsyncAPI /ws message ${name} has an unresolved $ref.`);
      } else if (!message.payload?.$ref) {
        errors.push(`AsyncAPI /ws message ${name} payload must use a schema $ref.`);
      } else if (!resolveLocalRef(asyncapi, message.payload.$ref)) {
        errors.push(`AsyncAPI /ws message ${name} has an unresolved payload $ref.`);
      }
    }
  }

  if (errors.length) {
    throw new Error(`API documentation completeness validation failed.\n  - ${errors.join('\n  - ')}`);
  }
}

function resolveLocalRef(document, reference) {
  if (!reference?.startsWith('#/')) {
    return undefined;
  }
  return reference
    .slice(2)
    .split('/')
    .map((token) => token.replaceAll('~1', '/').replaceAll('~0', '~'))
    .reduce((value, key) => value?.[key], document);
}

function resolveLocalObject(document, value, seen = new Set()) {
  if (!value || typeof value !== 'object' || Array.isArray(value) || !value.$ref) {
    return value;
  }
  if (seen.has(value.$ref)) {
    throw new Error(`Cyclic local reference ${value.$ref}.`);
  }
  const target = resolveLocalRef(document, value.$ref);
  if (target === undefined) {
    throw new Error(`Unresolved local reference ${value.$ref}.`);
  }
  const nextSeen = new Set(seen);
  nextSeen.add(value.$ref);
  const resolved = resolveLocalObject(document, target, nextSeen);
  const siblings = Object.fromEntries(
    Object.entries(value).filter(([key]) => key !== '$ref'),
  );
  return { ...structuredClone(resolved), ...structuredClone(siblings) };
}

function collectComponentRefs(value, refs = new Set()) {
  if (Array.isArray(value)) {
    value.forEach((entry) => collectComponentRefs(entry, refs));
    return refs;
  }
  if (!value || typeof value !== 'object') {
    return refs;
  }
  if (typeof value.$ref === 'string' && value.$ref.startsWith('#/components/')) {
    refs.add(value.$ref);
  }
  Object.values(value).forEach((entry) => collectComponentRefs(entry, refs));
  return refs;
}

const ASYNC_OPENAPI_SCHEMA_PREFIX = './openapi.yaml#/components/schemas/';

// materializeAsyncSharedSchemas keeps every HTTP/WebSocket shared payload
// byte-equivalent to its canonical OpenAPI schema without maintaining parallel
// copies. Authored AsyncAPI shared-schema markers point at openapi.yaml for
// source validation; generated bundles receive complete local schema graphs so
// each distributed contract remains independently consumable.
function materializeAsyncSharedSchemas(openapi, asyncapi) {
  const openapiSchemas = openapi.components?.schemas ?? {};
  const asyncSchemas = asyncapi.components?.schemas ?? {};
  const sharedNames = Object.keys(asyncSchemas)
    .filter((name) => Object.prototype.hasOwnProperty.call(openapiSchemas, name));
  if (!sharedNames.length) {
    return structuredClone(asyncapi);
  }
  for (const name of sharedNames) {
    const expected = `${ASYNC_OPENAPI_SCHEMA_PREFIX}${name}`;
    if (asyncSchemas[name]?.$ref !== expected) {
      throw new Error(`AsyncAPI shared schema ${name} must reference the canonical OpenAPI schema as ${expected}.`);
    }
  }

  const output = structuredClone(asyncapi);
  output.components ??= {};
  output.components.schemas ??= {};
  const pending = sharedNames.map((name) => `#/components/schemas/${name}`);
  const copied = new Set();
  while (pending.length) {
    const reference = pending.shift();
    if (copied.has(reference)) {
      continue;
    }
    const match = reference.match(/^#\/components\/schemas\/(.+)$/);
    if (!match) {
      continue;
    }
    const name = match[1].replaceAll('~1', '/').replaceAll('~0', '~');
    const schema = openapi.components?.schemas?.[name];
    if (!schema) {
      throw new Error(`OpenAPI shared schemas have an unresolved schema reference ${reference}.`);
    }
    copied.add(reference);
    output.components.schemas[name] = structuredClone(schema);
    for (const nested of collectComponentRefs(schema)) {
      if (nested.startsWith('#/components/schemas/') && !copied.has(nested)) {
        pending.push(nested);
      }
    }
  }
  return output;
}

function pruneOpenAPIComponents(filtered, original) {
  const base = structuredClone(filtered);
  delete base.components;
  const pending = [...collectComponentRefs(base)];
  const copied = new Set();
  const components = {};

  while (pending.length) {
    const reference = pending.shift();
    if (copied.has(reference)) {
      continue;
    }
    copied.add(reference);
    const tokens = reference.slice(2).split('/').map((token) => token.replaceAll('~1', '/').replaceAll('~0', '~'));
    const value = tokens.reduce((current, token) => current?.[token], original);
    if (value === undefined || tokens[0] !== 'components' || tokens.length < 3) {
      throw new Error(`Unable to retain referenced OpenAPI component ${reference}.`);
    }
    const [, group, ...nameTokens] = tokens;
    const name = nameTokens.join('/');
    components[group] ??= {};
    components[group][name] = structuredClone(value);
    for (const nested of collectComponentRefs(value)) {
      if (!copied.has(nested)) {
        pending.push(nested);
      }
    }
  }

  const securityNames = new Set();
  const collectSecurity = (security) => {
    for (const requirement of security ?? []) {
      Object.keys(requirement ?? {}).forEach((name) => securityNames.add(name));
    }
  };
  collectSecurity(base.security);
  for (const operation of openAPIOperations(base)) {
    collectSecurity(operation.operation.security ?? base.security);
  }
  for (const name of securityNames) {
    const scheme = original.components?.securitySchemes?.[name];
    if (!scheme) {
      throw new Error(`OpenAPI security scheme ${name} is used but not defined.`);
    }
    components.securitySchemes ??= {};
    components.securitySchemes[name] = structuredClone(scheme);
  }

  if (Object.keys(components).length) {
    base.components = components;
  }
  return base;
}

function publicOpenAPI(openapi) {
  const filtered = structuredClone(openapi);
  filtered.paths = {};
  const usedTags = new Set();

  for (const [route, pathItem] of Object.entries(openapi.paths ?? {})) {
    const nextPath = {};
    for (const [key, value] of Object.entries(pathItem ?? {})) {
      if (!HTTP_METHODS.has(key.toLowerCase())) {
        nextPath[key] = structuredClone(value);
        continue;
      }
      if (!externallyDocumented(value, pathItem)) {
        continue;
      }
      nextPath[key] = structuredClone(value);
      for (const tag of value.tags ?? []) {
        usedTags.add(tag);
      }
    }
    if (Object.keys(nextPath).some((key) => HTTP_METHODS.has(key.toLowerCase()))) {
      filtered.paths[route] = nextPath;
    }
  }

  filtered.tags = (openapi.tags ?? []).filter((tag) => usedTags.has(tag.name));
  if (Array.isArray(filtered['x-tagGroups'])) {
    filtered['x-tagGroups'] = filtered['x-tagGroups']
      .map((group) => ({
        ...group,
        tags: (group.tags ?? []).filter((tag) => usedTags.has(tag)),
      }))
      .filter((group) => group.tags.length);
  }
  delete filtered.webhooks;
  return pruneOpenAPIComponents(filtered, openapi);
}

function publicAsyncAPI(asyncapi) {
  const filtered = structuredClone(asyncapi);
  filtered.channels = {};
  const retainedChannelRefs = new Set();

  for (const [key, channel] of Object.entries(asyncapi.channels ?? {})) {
    if (!externallyDocumented(channel)) {
      continue;
    }
    filtered.channels[key] = structuredClone(channel);
    retainedChannelRefs.add(`#/channels/${key.replaceAll('~', '~0').replaceAll('/', '~1')}`);
  }

  if (String(asyncapi.asyncapi ?? '').startsWith('3.')) {
    filtered.operations = {};
    for (const [key, operation] of Object.entries(asyncapi.operations ?? {})) {
      const reference = operation?.channel?.$ref;
      const referencedChannel = resolveLocalRef(asyncapi, reference);
      if (
        externallyDocumented(operation, referencedChannel)
        && (!reference || retainedChannelRefs.has(reference))
      ) {
        filtered.operations[key] = structuredClone(operation);
      }
    }
  } else {
    for (const channel of Object.values(filtered.channels)) {
      for (const action of ['publish', 'subscribe']) {
        if (channel?.[action] && visibilityOf(channel[action], channel) !== 'public') {
          delete channel[action];
        }
      }
    }
  }

  return pruneGenericComponents(filtered, asyncapi);
}

