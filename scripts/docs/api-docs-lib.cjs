async function lintDocumentation(options) {
  const files = inputPaths(options);
  for (const file of [files.openapi, files.asyncapi, files.redocly, files.server, files.version]) {
    if (!fs.existsSync(file)) {
      throw new Error(`Required API documentation input does not exist: ${file}`);
    }
  }
  let redoclyOutput = '';
  if (!options.skipRedocly) {
    redoclyOutput = runRedocly(files.docsRoot, [
      'lint',
      files.openapi,
      '--config',
      files.redocly,
    ]);
  }
  const openapi = readDocument(files.openapi);
  const asyncapi = materializeAsyncSharedSchemas(
    openapi,
    await validateAsyncAPI(files.asyncapi),
  );
  assertCompleteness(openapi, asyncapi);
  assertVisibility(openapi, asyncapi);
  if (!options.skipVersionParity) {
    assertVersionParity({
      sourceText: fs.readFileSync(files.version, 'utf8'),
      openapi,
      asyncapi,
    });
  }
  const parity = assertRouteParity({
    sourceText: fs.readFileSync(files.server, 'utf8'),
    openapi,
    asyncapi,
  });
  assertCodeAnchors({
    repoRoot: options.repoRoot,
    sourceText: fs.readFileSync(files.server, 'utf8'),
    openapi,
    asyncapi,
  });
  return { ...parity, redoclyOutput };
}

async function bundleDocumentation(options) {
  const files = inputPaths(options);
  fs.rmSync(files.build, { recursive: true, force: true });
  fs.mkdirSync(files.build, { recursive: true });
  const openapiOutput = path.join(files.build, 'openapi.bundle.yaml');
  if (options.skipRedocly) {
    writeText(openapiOutput, stableYAML(readDocument(files.openapi)));
  } else {
    runRedocly(files.docsRoot, [
      'bundle',
      files.openapi,
      '--config',
      files.redocly,
      '--output',
      openapiOutput,
    ]);
  }
  const openapi = readDocument(openapiOutput);
  const asyncapi = materializeAsyncSharedSchemas(
    openapi,
    await validateAsyncAPI(files.asyncapi),
  );
  const asyncapiOutput = path.join(files.build, 'asyncapi.bundle.yaml');
  writeText(asyncapiOutput, stableYAML(asyncapi));
  return { openapi: openapiOutput, asyncapi: asyncapiOutput };
}

