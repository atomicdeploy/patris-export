function chooseExampleOperation(openapi, requireSecurity = false) {
  const operations = openAPIOperations(openapi);
  const secured = (entry) => {
    const requirements = entry.operation.security ?? openapi.security ?? [];
    return requirements.some((requirement) => Object.keys(requirement).length > 0);
  };
  const candidates = operations.filter((entry) => secured(entry) === requireSecurity);
  if (!candidates.length) {
    return undefined;
  }
  const priorities = requireSecurity
    ? ['/api/recent-sales', '/api/product-sync', '/api/source/manifest']
    : ['/api/records', '/api/status', '/api/info'];
  return candidates.sort((left, right) => {
    const leftPriority = priorities.indexOf(left.path);
    const rightPriority = priorities.indexOf(right.path);
    const leftRank = leftPriority === -1 ? priorities.length : leftPriority;
    const rightRank = rightPriority === -1 ? priorities.length : rightPriority;
    return leftRank - rightRank
      || Number(left.method !== 'GET') - Number(right.method !== 'GET')
      || routeKey(left).localeCompare(routeKey(right));
  })[0];
}

function schemaExample(schema, document, depth = 0) {
  if (!schema || depth > 5) {
    return null;
  }
  if (schema.example !== undefined) {
    return schema.example;
  }
  if (schema.default !== undefined) {
    return schema.default;
  }
  if (schema.const !== undefined) {
    return schema.const;
  }
  if (Array.isArray(schema.examples) && schema.examples.length) {
    return schema.examples[0];
  }
  if (schema.$ref) {
    return schemaExample(resolveLocalRef(document, schema.$ref), document, depth + 1);
  }
  if (schema.oneOf?.length || schema.anyOf?.length) {
    return schemaExample((schema.oneOf ?? schema.anyOf)[0], document, depth + 1);
  }
  if (schema.type === 'array') {
    return [schemaExample(schema.items, document, depth + 1)];
  }
  if (schema.type === 'object' || schema.properties) {
    return Object.fromEntries(
      Object.entries(schema.properties ?? {}).map(([key, value]) => [
        key,
        schemaExample(value, document, depth + 1),
      ]),
    );
  }
  if (schema.enum?.length) {
    return schema.enum[0];
  }
  if (schema.type === 'boolean') {
    return false;
  }
  if (schema.type === 'integer' || schema.type === 'number') {
    return 0;
  }
  return schema.format === 'date-time' ? '2026-01-01T00:00:00Z' : 'example';
}

function exampleRequest(openapi, entry) {
  const serverURL = openapi.servers?.[0]?.url ?? 'http://127.0.0.1:18080';
  let requestPath = entry.path;
  const parameters = [...(entry.pathItem.parameters ?? []), ...(entry.operation.parameters ?? [])];
  for (const parameter of parameters.filter((value) => value.in === 'path')) {
    const value = parameter.example
      ?? parameter.schema?.example
      ?? parameter.schema?.enum?.[0]
      ?? parameter.name;
    requestPath = requestPath.replace(`{${parameter.name}}`, encodeURIComponent(String(value)));
  }
  const query = new URLSearchParams();
  for (const parameter of parameters.filter((value) => value.in === 'query' && value.required)) {
    const value = parameter.example
      ?? parameter.schema?.example
      ?? parameter.schema?.default
      ?? parameter.schema?.enum?.[0]
      ?? 'example';
    query.set(parameter.name, String(value));
  }
  if ([...query].length) {
    requestPath += `?${query.toString()}`;
  }

  const requestContent = entry.operation.requestBody?.content ?? {};
  const contentType = Object.keys(requestContent)[0];
  const media = contentType ? requestContent[contentType] : undefined;
  const body = media?.example
    ?? Object.values(media?.examples ?? {})[0]?.value
    ?? schemaExample(media?.schema, openapi);
  const responseContent = Object.values(entry.operation.responses ?? {})
    .flatMap((response) => Object.keys(response?.content ?? {}));
  const jsonMediaType = responseContent.find((mediaType) => (
    mediaType === 'application/json' || /^[^;]+\+json(?:;|$)/i.test(mediaType)
  ));
  const accept = jsonMediaType
    ? jsonMediaType
    : responseContent[0] ?? '*/*';
  const requirements = entry.operation.security ?? openapi.security ?? [];
  const securityNames = requirements.flatMap((requirement) => Object.keys(requirement));
  const headers = { Accept: accept };
  if (contentType) {
    headers['Content-Type'] = contentType;
  }
  for (const name of securityNames) {
    const scheme = openapi.components?.securitySchemes?.[name];
    if (scheme?.type === 'http' && scheme.scheme?.toLowerCase() === 'bearer') {
      headers.Authorization = 'Bearer ${PATRIS_EXPORT_API_TOKEN}';
    } else if (scheme?.type === 'apiKey' && scheme.in === 'header') {
      headers[scheme.name] = '${PATRIS_EXPORT_API_TOKEN}';
    }
  }
  return {
    method: entry.method,
    operationId: entry.operation.operationId,
    serverURL,
    path: requestPath,
    headers,
    body,
    responseIsJSON: Boolean(jsonMediaType),
  };
}

function shellQuote(value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`;
}

function shellDoubleQuoteLiteral(value) {
  return String(value)
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('$', '\\$')
    .replaceAll('`', '\\`');
}

const TOKEN_PLACEHOLDER = '${PATRIS_EXPORT_API_TOKEN}';

function tokenPrefix(value) {
  return value.includes(TOKEN_PLACEHOLDER)
    ? value.slice(0, value.indexOf(TOKEN_PLACEHOLDER))
    : undefined;
}

function renderShellHeaders(headers, indentation) {
  return Object.entries(headers).map(([name, value]) => {
    const prefix = tokenPrefix(value);
    if (prefix !== undefined) {
      return `${indentation}-H "${name}: ${prefix}$PATRIS_EXPORT_API_TOKEN"`;
    }
    return `${indentation}-H ${shellQuote(`${name}: ${value}`)}`;
  });
}

