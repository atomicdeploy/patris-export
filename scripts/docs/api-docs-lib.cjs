function writeChecksums(directory) {
  const checksumFile = path.join(directory, 'SHA256SUMS');
  const lines = listFiles(directory)
    .filter((file) => file !== checksumFile)
    .map((file) => `${sha256File(file)}  ${posixRelative(directory, file)}`)
    .sort();
  writeText(checksumFile, `${lines.join('\n')}\n`);
}

async function createDeterministicZip(source, output, rootName) {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const stream = fs.createWriteStream(output);
  const archive = new ZipArchive({
    forceLocalTime: false,
    zlib: { level: 9 },
  });
  const completed = new Promise((resolve, reject) => {
    stream.on('close', resolve);
    stream.on('error', reject);
    archive.on('error', reject);
  });
  archive.pipe(stream);

  for (const file of listFiles(source)) {
    // Archiver can finish compressed entries in a different order when many
    // append calls are queued together. Wait for each entry event before
    // appending the next sorted buffer to preserve both compression and bytes.
    await new Promise((resolve, reject) => {
      const onEntry = () => {
        archive.off('error', onError);
        resolve();
      };
      const onError = (error) => {
        archive.off('entry', onEntry);
        reject(error);
      };
      archive.once('entry', onEntry);
      archive.once('error', onError);
      archive.append(fs.readFileSync(file), {
        date: ZIP_EPOCH,
        mode: 0o644,
        name: `${rootName}/${posixRelative(source, file)}`,
      });
    });
  }
  await archive.finalize();
  await completed;
}

async function validateAsyncAPI(asyncapiFile) {
  const parser = new AsyncAPIParser();
  const source = fs.readFileSync(asyncapiFile, 'utf8');
  const result = await parser.parse(source, {
    source: asyncapiFile,
  });
  const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === DiagnosticSeverity.Error);
  if (!result.document || errors.length) {
    const detail = errors.map((diagnostic) => `${diagnostic.path?.join('.') || '/'}: ${diagnostic.message}`).join('\n');
    throw new Error(`AsyncAPI validation failed for ${asyncapiFile}.\n${detail}`);
  }
  // Return the authored form so semantic validation and distribution preserve
  // deliberate $ref boundaries instead of the parser's resolved model.
  return path.extname(asyncapiFile).toLowerCase() === '.json'
    ? JSON.parse(source)
    : YAML.parse(source);
}

function runRedocly(docsRoot, args) {
  const cli = path.join(docsRoot, 'node_modules', '@redocly', 'cli', 'bin', 'cli.js');
  const result = spawnSync(process.execPath, [cli, ...args], {
    cwd: docsRoot,
    encoding: 'utf8',
    stdio: 'pipe',
  });
  if (result.status !== 0) {
    throw new Error([
      `Redocly CLI failed: redocly ${args.join(' ')}`,
      result.stdout,
      result.stderr,
    ].filter(Boolean).join('\n'));
  }
  return result.stdout.trim();
}

