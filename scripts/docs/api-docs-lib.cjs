function assertSamplesSanitized(directory) {
  const violations = [];
  for (const file of listFiles(directory)) {
    const text = fs.readFileSync(file, 'utf8');
    const patterns = [
      /Authorization:\s*Bearer\s+(?!['"`]?\$|['"`]?\$\{|['"`]?Environment|['"`]?getenv)[A-Za-z0-9._~+/-]{12,}/gi,
      /\b(?:token|api[_-]?key|secret)\s*[:=]\s*['"][A-Za-z0-9._~+/-]{16,}['"]/gi,
    ];
    for (const pattern of patterns) {
      if (pattern.test(text)) {
        violations.push(posixRelative(directory, file));
        break;
      }
    }
  }
  if (violations.length) {
    throw new Error(`Generated examples appear to contain credential values: ${violations.join(', ')}`);
  }
}

